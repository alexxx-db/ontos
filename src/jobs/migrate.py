"""Apply the app's Alembic migrations to Lakebase as the job's run-as identity.

Arguments: the bundle's workspace file path, the Lakebase branch name, the
database, and the Postgres schema. Run by `databricks bundle run migrate` after
`bundle deploy` and before the app starts.

Hello Abacus runs Atlas here; ontos keeps Alembic (its revision chain predates
the alignment). This job reuses the app's own init_db(), which ensures the
database and schema exist and runs `alembic upgrade head`, so there is one
migration implementation. The OAuth credential is generated by the app code
itself through the Databricks SDK, so no secret reaches argv.
"""

import os
import sys

from databricks.sdk import WorkspaceClient

bundle_root, branch, database_id, pgschema = sys.argv[1:5]
# postgres_databases.app.id is the resource name, projects/<p>/branches/<b>/databases/<db>;
# the Postgres database itself is its last segment.
database = database_id.rsplit("/", 1)[-1]

w = WorkspaceClient()
endpoint = f"{branch}/endpoints/primary"
host = w.postgres.get_endpoint(name=endpoint).status.hosts.host
user = w.current_user.me().user_name
print(f"alembic: applying migrations to {host}/{database} schema {pgschema} as {user}")

# The app runs `python backend/src/app.py` with PYTHONPATH=./backend; the job
# puts the synced artifact's backend on the path the same way.
sys.path.insert(0, os.path.join(bundle_root, "app_artifact", "backend"))

# Settings the app resolves from its env in the Apps container. ENV=PROD selects
# Lakebase OAuth (not LOCAL password auth); LAKEBASE_INSTANCE_NAME is the
# documented fallback that resolves the branch to its endpoint.
os.environ["LAKEBASE_INSTANCE_NAME"] = branch
os.environ["PGHOST"] = host
os.environ["PGDATABASE"] = database
os.environ["PGSCHEMA"] = pgschema
os.environ["ENV"] = "PROD"
os.environ.setdefault("APP_AUDIT_LOG_DIR", "/tmp/ontos_audit_logs")
# Required Settings fields the migration path does not use.
os.environ.setdefault("DATABRICKS_HOST", w.config.host or "")
os.environ.setdefault("DATABRICKS_WAREHOUSE_ID", "")

from src.common.database import init_db

init_db()
